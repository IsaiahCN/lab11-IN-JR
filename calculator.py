import math

def add(a, b): 
    return a+b
def mul(a, b):
    return a*b
def subtract(a, b):
    return a-b
def div(a, b):
    return a/b
def logarithm(a, b):
    return a*math.log(b)
def exp(a,b):
    return a**b
def hypotenuse(a, b):
    c= (a**2)+(b**2)
    return c **(1/2)
def square_root(a):
    return math.sqrt(a)